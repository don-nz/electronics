#!/usr/bin/env python3
"""Build cert_iii/assets/shapes.js from the master files in cert_iii/assets/shapes/*.html.

Why: cross-file SVG <use> and fetch() are blocked under file://, so quiz pages
used to hold pasted copies of the shapes they needed. shapes.js carries the
<defs> of every master file as a named set; a page asks for the sets it needs
and the shapes are injected into a hidden <svg> at load. The masters stay the
single source of truth — re-run this script after editing one.

    python3 tools/build_shapes.py          # (re)write assets/shapes.js
    python3 tools/build_shapes.py --check  # exit 1 if shapes.js is out of date

Ids that appear in more than one master file must have identical markup
(e.g. the shared "glow" filter); otherwise the build fails so the clash is
resolved by renaming, not silently shadowed.
"""
import glob, json, os, re, sys, hashlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'cert_iii', 'assets', 'shapes')
OUT = os.path.join(ROOT, 'cert_iii', 'assets', 'shapes.js')


def top_level_ids(markup):
    """Ids of the direct children of a <defs> body (what Shapes dedupes on)."""
    ids, depth, i = [], 0, 0
    for m in re.finditer(r'<(/?)([\w:-]+)([^>]*?)(/?)>', markup):
        close, _name, attrs, selfclose = m.groups()
        if close:
            depth -= 1
            continue
        if depth == 0:
            idm = re.search(r'\sid="([^"]+)"', attrs)
            if idm:
                ids.append((idm.group(1), m.start()))
        if not selfclose:
            depth += 1
    return [i for i, _ in ids]


def element_blocks(markup):
    """Split a defs body into {id: markup} for top-level elements that carry an id."""
    out, depth, start, cur = {}, 0, None, None
    for m in re.finditer(r'<(/?)([\w:-]+)([^>]*?)(/?)>', markup):
        close, _name, attrs, selfclose = m.groups()
        if close:
            depth -= 1
            if depth == 0 and cur is not None:
                out[cur] = markup[start:m.end()]
                cur = None
            continue
        if depth == 0:
            idm = re.search(r'\sid="([^"]+)"', attrs)
            start = m.start()
            cur = idm.group(1) if idm else None
            if selfclose and cur:
                out[cur] = markup[start:m.end()]
                cur = None
        if not selfclose:
            depth += 1
    return out


def read_sets():
    sets = {}
    for path in sorted(glob.glob(os.path.join(SRC, '*.html'))):
        name = os.path.splitext(os.path.basename(path))[0]
        text = open(path, encoding='utf-8').read()
        # comments first: the masters' header comments mention "<defs>" in prose
        text = re.sub(r'<!--.*?-->', '', text, flags=re.S)
        m = re.search(r'<defs[^>]*>(.*?)</defs>', text, re.S)
        if not m:
            continue
        body = m.group(1)
        # masters carry a <style>:root{--colour-…}</style> so they render standalone;
        # injected into a page it would override that page's own (themed) tokens
        body = re.sub(r'<style\b[^>]*>.*?</style>', '', body, flags=re.S)
        body = re.sub(r'\n\s*\n+', '\n', body).strip()
        sets[name] = body
    return sets


def main(check=False):
    sets = read_sets()
    seen = {}      # id -> (set, normalised markup)
    clashes = []
    for name, body in sets.items():
        for i, blk in element_blocks(body).items():
            norm = re.sub(r'\s+', ' ', blk)
            if i in seen and seen[i][1] != norm:
                clashes.append((i, seen[i][0], name))
            seen.setdefault(i, (name, norm))
    for name, body in sets.items():
        counts = {}
        for i in re.findall(r'\sid="([^"]+)"', body):
            counts[i] = counts.get(i, 0) + 1
        dups = sorted(i for i, c in counts.items() if c > 1)
        if dups:
            print(f'warning: {name}.html defines duplicate ids inside itself: ' + ', '.join(dups))
    if clashes:
        print('ID CLASHES (same id, different markup) — rename one:')
        for i, a, b in clashes:
            print(f'  #{i}: {a} vs {b}')
        return 1

    lines = [
        '/* GENERATED by tools/build_shapes.py from assets/shapes/*.html — do not edit by hand.',
        '',
        '   Shared SVG shape library. Cross-file <use> and fetch() are blocked on',
        '   file://, so shapes are carried as strings here and injected into a hidden',
        '   <svg> on the page itself — after that, <use href="#gate-nor-trad"> etc.',
        '   work exactly as if the defs had been pasted into the page.',
        '',
        '   Usage (plain script, same load pattern as theme-init.js):',
        '     <script src="…/assets/shapes.js"></script>',
        '     <script>Shapes.use("logic-gates", "flip-flops");</script>',
        '',
        '   Per-page scaling — the masters are drawn at 1:1; a page that wants them',
        '   bigger passes a trailing options object (id globs -> SVG transform):',
        '     Shapes.use("logic-gates", { transform: { "*-trad": "scale(1.5)", "*-iec": "scale(1.3)" } });',
        '   Only top-level shapes without a transform of their own are touched.',
        '',
        '   Shapes.sets()       -> array of set names',
        '   Shapes.ids(name)    -> ids a set defines',
        '   Ids already present in the document (e.g. a page\'s own pasted copy) are',
        '   skipped, so pages can migrate one at a time. Edit the masters in',
        '   assets/shapes/, then run:  python3 tools/build_shapes.py',
        '*/',
        '(function () {',
        '  var SETS = {',
    ]
    items = []
    for name, body in sets.items():
        items.append(f'    {json.dumps(name)}: {json.dumps(body, ensure_ascii=False)}')
    lines.append(',\n'.join(items))
    lines += [
        '  };',
        '',
        '  var HOST_ID = "shapes-js-defs";',
        '  var wanted = [];   // [{ name, transform }]',
        '',
        '  function globRe(g) {',
        '    return new RegExp("^" + g.replace(/[.+?^${}()|[\\]\\\\]/g, "\\\\$&").replace(/\\*/g, ".*") + "$");',
        '  }',
        '',
        '  function host() {',
        '    var h = document.getElementById(HOST_ID);',
        '    if (h) return h;',
        '    var NS = "http://www.w3.org/2000/svg";',
        '    var svg = document.createElementNS(NS, "svg");',
        '    svg.setAttribute("id", HOST_ID);',
        '    svg.setAttribute("width", "0");',
        '    svg.setAttribute("height", "0");',
        '    svg.setAttribute("aria-hidden", "true");',
        '    // not display:none — that breaks filters/gradients referenced via url(#id)',
        '    svg.style.cssText = "position:absolute;width:0;height:0;overflow:hidden";',
        '    svg.appendChild(document.createElementNS(NS, "defs"));',
        '    document.body.insertBefore(svg, document.body.firstChild);',
        '    return svg;',
        '  }',
        '',
        '  function inject(job) {',
        '    var name = job.name;',
        '    var defs = host().querySelector("defs");',
        '    if (defs.getAttribute("data-" + name)) return;',
        '    defs.setAttribute("data-" + name, "1");',
        '    var tmp = document.createElementNS("http://www.w3.org/2000/svg", "svg");',
        '    tmp.innerHTML = SETS[name];',
        '    Array.prototype.slice.call(tmp.childNodes).forEach(function (n) {',
        '      if (n.nodeType === 1 && n.id && document.getElementById(n.id)) return; // already on the page',
        '      if (n.nodeType === 1 && n.id && job.transform && !n.hasAttribute("transform")) {',
        '        Object.keys(job.transform).some(function (g) {',
        '          if (globRe(g).test(n.id)) { n.setAttribute("transform", job.transform[g]); return true; }',
        '        });',
        '      }',
        '      defs.appendChild(n);',
        '    });',
        '  }',
        '',
        '  function flush() {',
        '    wanted.forEach(inject);',
        '    wanted = [];',
        '  }',
        '',
        '  window.Shapes = {',
        '    use: function () {',
        '      var names = Array.prototype.slice.call(arguments), opts = null;',
        '      if (names.length && typeof names[names.length - 1] === "object") opts = names.pop();',
        '      names.forEach(function (n) {',
        '        if (!SETS[n]) { console.error("Shapes.use: unknown set \\"" + n + "\\" (have: " + Object.keys(SETS).join(", ") + ")"); return; }',
        '        wanted.push({ name: n, transform: opts && opts.transform });',
        '      });',
        '      if (document.body) flush();',
        '      else document.addEventListener("DOMContentLoaded", flush);',
        '    },',
        '    sets: function () { return Object.keys(SETS); },',
        '    ids: function (name) {',
        '      var tmp = document.createElementNS("http://www.w3.org/2000/svg", "svg");',
        '      tmp.innerHTML = SETS[name] || "";',
        '      return Array.prototype.slice.call(tmp.querySelectorAll("[id]")).map(function (e) { return e.id; });',
        '    }',
        '  };',
        '})();',
        '',
    ]
    out = '\n'.join(lines)
    if check:
        cur = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        if cur != out:
            print('assets/shapes.js is out of date — run: python3 tools/build_shapes.py')
            return 1
        print('assets/shapes.js is up to date')
        return 0
    open(OUT, 'w', encoding='utf-8').write(out)
    print(f'wrote {os.path.relpath(OUT, ROOT)}: {len(sets)} sets, {len(seen)} shapes, {len(out)//1024} KB')
    return 0


if __name__ == '__main__':
    sys.exit(main(check='--check' in sys.argv))
